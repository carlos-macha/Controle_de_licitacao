CREATE TABLE LICITACAO (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NUMERO_EDITAL VARCHAR(30) NOT NULL,
    NOME VARCHAR(100) NOT NULL,
    DESCRICAO VARCHAR(500) NOT NULL,
    CODIGO_LICITACAO VARCHAR(30) NOT NULL,
    ORGAO_COMPETENTE VARCHAR(150) NOT NULL,
    DATA_CERTAME DATE NOT NULL,
    LOGRADOURO VARCHAR(150) NOT NULL,
    NUMERO VARCHAR(10) NOT NULL,
    BAIRRO VARCHAR(100) NOT NULL,
    CIDADE VARCHAR(100) NOT NULL,
    ESTADO CHAR(2) NOT NULL,
    CEP VARCHAR(9) NOT NULL,
    COMPLEMENTO VARCHAR(100)
);

CREATE TABLE CONCORRENTE (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR(150) NOT NULL,
    CNPJ CHAR(14) NOT NULL,
    EMAIL VARCHAR(150) NOT NULL,
    TELEFONE VARCHAR(15) NOT NULL,
    CELULAR VARCHAR(15) NOT NULL,
    LOGRADOURO VARCHAR(150) NOT NULL,
    NUMERO VARCHAR(10) NOT NULL,
    BAIRRO VARCHAR(100) NOT NULL,
    CIDADE VARCHAR(100) NOT NULL,
    ESTADO CHAR(2) NOT NULL,
    CEP VARCHAR(9) NOT NULL,
    COMPLEMENTO VARCHAR(100)
);

CREATE TABLE PRODUTO (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_PRODUTO VARCHAR(30) NOT NULL,
    DESCRICAO VARCHAR(200) NOT NULL,
    MARCA VARCHAR(100) NOT NULL,
    MODELO VARCHAR(100) NOT NULL,
    PRECO_BASE NUMERIC(15,2) NOT NULL,
    OBSERVACAO VARCHAR(500)
);

CREATE TABLE LICITACAO_PRODUTO (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_LICITACAO INTEGER NOT NULL,
    CODIGO_PRODUTO INTEGER NOT NULL,
    QUANTIDADE NUMERIC(15,3) NOT NULL,
    VALOR_UNITARIO_REFERENCIA NUMERIC(15,2) NOT NULL,
    VALOR_TOTAL_REFERENCIA NUMERIC(15,2) NOT NULL
);

CREATE TABLE RESULTADO_LICITACAO (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_LICITACAO INTEGER NOT NULL,
    CODIGO_CONCORRENTE INTEGER NOT NULL,
    CODIGO_PRODUTO INTEGER NOT NULL,
    PRECO_GANHO NUMERIC(15,2) NOT NULL,
    DATA_RESULTADO DATE NOT NULL
);

