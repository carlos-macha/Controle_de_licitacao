CREATE TABLE LICITACAO (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PREGAO VARCHAR(100) NOT NULL,
    PROCESSO_LICITATORIO VARCHAR(100) NOT NULL,
    MUNICIPIO VARCHAR(100) NOT NULL,
    ESTADO CHAR(2),
    DATA_CERTAME DATE,
    LOGRADOURO VARCHAR(150),
    NUMERO VARCHAR(10),
    BAIRRO VARCHAR(100),
    CIDADE VARCHAR(100),
    CEP VARCHAR(9),
    COMPLEMENTO VARCHAR(100)
);


CREATE TABLE CONCORRENTE (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR(150) NOT NULL,
    CNPJ CHAR(14) NOT NULL UNIQUE,
    LOGRADOURO VARCHAR(150),
    NUMERO VARCHAR(10),
    BAIRRO VARCHAR(100),
    CIDADE VARCHAR(100),
    ESTADO CHAR(2),
    CEP VARCHAR(9),
    COMPLEMENTO VARCHAR(100),
    EMAIL VARCHAR(150),
    TELEFONE VARCHAR(15),
    CELULAR VARCHAR(15)
);


CREATE TABLE ITEM_LICITACAO (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LICITACAO_ID INTEGER NOT NULL,
    ITEM INTEGER NOT NULL,
    DESCRICAO VARCHAR(1000) NOT NULL,
    MARCA VARCHAR(500),
    MODELO VARCHAR(500),
    QUANTIDADE NUMERIC(15,3) NOT NULL,
    UNIDADE VARCHAR(20) NOT NULL,
    OBSERVACAO VARCHAR(1000),
    CONSTRAINT UQ_ITEM_LICITACAO
        UNIQUE (LICITACAO_ID, ITEM)
);


CREATE TABLE RESULTADO_LICITACAO (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ITEM_LICITACAO_ID INTEGER NOT NULL,
    CONCORRENTE_ID INTEGER NOT NULL,
    PRECO_GANHO NUMERIC(15,2) NOT NULL,
    VALOR_TOTAL_LANCE NUMERIC(15,2) NOT NULL,
    VALOR_ORCADO NUMERIC(15,2) NOT NULL,
    VALOR_TOTAL_ORCADO NUMERIC(15,2) NOT NULL,
    ECONOMIA_PERCENTUAL NUMERIC(5,2) NOT NULL,
    ECONOMIA_REAIS NUMERIC(15,2) NOT NULL,
    DATA_RELATORIO DATE NOT NULL,
    HORA_RELATORIO TIME NOT NULL
);


ALTER TABLE ITEM_LICITACAO
ADD CONSTRAINT FK_ITEM_LICITACAO
FOREIGN KEY (LICITACAO_ID)
REFERENCES LICITACAO(ID);


ALTER TABLE RESULTADO_LICITACAO
ADD CONSTRAINT FK_RESULTADO_CONCORRENTE
FOREIGN KEY (CONCORRENTE_ID)
REFERENCES CONCORRENTE(ID);


CREATE TABLE USUARIO (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LOGIN VARCHAR(50) NOT NULL UNIQUE,
    NOME VARCHAR(100) NOT NULL,
    SENHA_HASH VARCHAR(255) NOT NULL,
    ATIVO CHAR(1) DEFAULT 'A' NOT NULL,
    DATA_CADASTRO DATE DEFAULT CURRENT_DATE NOT NULL,
    DATA_ALTERACAO DATE,
    PERFIL VARCHAR(20) DEFAULT 'USER' NOT NULL
);


CREATE TRIGGER TRG_USUARIO_UPDATE
FOR USUARIO
ACTIVE BEFORE UPDATE
POSITION 0
AS
BEGIN
    NEW.DATA_ALTERACAO = CURRENT_DATE;
END